/*
  Generates src/onboarding/tanzil.ts from the official Tanzil downloads.

  ONBOARDING ONLY, AND TEMPORARY. Approved by the owner (issue #3) for the
  onboarding heroes until Quran Foundation Content Sync is live, then this
  module and this script are deleted. Never use it to build the Read tab.

  The Quran text is copied mechanically, byte for byte, from the downloaded
  file. Nothing here edits, normalises or retypes it: that is both the
  authenticity rule and Tanzil's licence ("CHANGING IT IS NOT ALLOWED").

  Usage:
    1. Download, agreeing to the terms on tanzil.net:
       Text:      https://tanzil.net/pub/download/index.php?quranType=uthmani&outType=txt-2&agree=true
       Metadata:  https://tanzil.net/res/text/metadata/quran-data.xml
    2. npx tsx scripts/make-tanzil-onboarding.ts <quran-uthmani.txt> <quran-data.xml> <download date YYYY-MM-DD>
*/
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const [textPath, dataPath, downloaded] = process.argv.slice(2);
if (!textPath || !dataPath || !/^\d{4}-\d{2}-\d{2}$/.test(downloaded ?? "")) {
  console.error("usage: make-tanzil-onboarding.ts <quran-uthmani.txt> <quran-data.xml> <YYYY-MM-DD>");
  process.exit(1);
}

const textRaw = readFileSync(textPath);
const dataRaw = readFileSync(dataPath);
const sha = (b: Buffer) => createHash("sha256").update(b).digest("hex");

/* ---------- text ---------- */

const text = textRaw.toString("utf8");
const version = /Tanzil Quran Text \(([^)]+)\)/.exec(text)?.[1];
if (!version) throw new Error("No Tanzil version line in the text file");

/* The licence block, exactly as it appears at the end of the download. */
const licence = text
  .split("\n")
  .filter((l) => l.startsWith("#"))
  .join("\n");

/* The only ayahs onboarding uses. Read hero: 1:1 to 1:3. Ask hero: 13:28, 94:5. */
const WANT = ["1:1", "1:2", "1:3", "13:28", "94:5"];
const ayahs: Record<string, string> = {};
for (const line of text.split("\n")) {
  const m = /^(\d+)\|(\d+)\|(.*)$/.exec(line.replace(/\r$/, ""));
  if (!m) continue;
  const key = `${m[1]}:${m[2]}`;
  if (WANT.includes(key)) ayahs[key] = m[3];
}
for (const k of WANT) if (!ayahs[k]) throw new Error(`Missing ${k}`);

/* ---------- metadata ---------- */

const xml = dataRaw.toString("utf8");
const attr = (tag: string, name: string) => new RegExp(`${name}="([^"]*)"`).exec(tag)?.[1] ?? "";

const surahs = [...xml.matchAll(/<sura [^>]*\/>/g)].map((m) => ({
  n: Number(attr(m[0], "index")),
  ayahs: Number(attr(m[0], "ayas")),
  start: Number(attr(m[0], "start")),
  ar: attr(m[0], "name"),
  en: attr(m[0], "tname"),
}));
if (surahs.length !== 114) throw new Error(`Expected 114 surahs, got ${surahs.length}`);

const juz = [...xml.matchAll(/<juz [^>]*\/>/g)].map((m) => {
  const s = Number(attr(m[0], "sura"));
  const a = Number(attr(m[0], "aya"));
  /* As a global ayah index from 0, the same numbering as a surah's start. */
  return surahs[s - 1].start + a - 1;
});
if (juz.length !== 30) throw new Error(`Expected 30 juz, got ${juz.length}`);

const total = surahs.reduce((n, s) => n + s.ayahs, 0);
if (total !== 6236) throw new Error(`Expected 6236 ayahs, got ${total}`);

/* ---------- write ---------- */

const out = `/*
  GENERATED by scripts/make-tanzil-onboarding.ts. Do not edit by hand.

  ONBOARDING ONLY, AND TEMPORARY (issue #3). To be replaced by Quran Foundation
  Content Sync once credentials exist, then deleted. Not for the Read tab.

  Source: Tanzil Project, tanzil.net
    Text:     ${version}, downloaded ${downloaded}
              https://tanzil.net/pub/download/index.php?quranType=uthmani&outType=txt-2&agree=true
              sha256 ${sha(textRaw)}
    Metadata: quran-data.xml (${/version="([^"]*)"/.exec(xml)?.[1] ?? "unknown"}), downloaded ${downloaded}
              https://tanzil.net/res/text/metadata/quran-data.xml
              sha256 ${sha(dataRaw)}

  The ayah strings below are copied verbatim from the download. Tanzil's terms
  forbid changing the text and require its notice in every copy, so it follows.

${licence
  .split("\n")
  .map((l) => `  ${l}`)
  .join("\n")}
*/

export const TANZIL_CREDIT = {
  name: "Tanzil Project",
  url: "https://tanzil.net",
  version: ${JSON.stringify(version)},
} as const;

/* Verbatim Uthmani text, keyed "surah:ayah". */
export const AYAHS = ${JSON.stringify(ayahs, null, 2)} as const;

export type SurahMeta = { n: number; ayahs: number; start: number; ar: string; en: string };

/* All 114, in mushaf order. start is the global index of the surah's first ayah, from 0. */
export const SURAHS: SurahMeta[] = ${JSON.stringify(surahs)};

/* Global index, from 0, of the first ayah of each juz. */
export const JUZ_STARTS: number[] = ${JSON.stringify(juz)};

export const TOTAL_AYAHS = ${total};
`;

const target = resolve(__dirname, "../src/onboarding/tanzil.ts");
writeFileSync(target, out);
console.log(`wrote ${target}`);
console.log(`text ${version} sha256 ${sha(textRaw)}`);
console.log(`metadata sha256 ${sha(dataRaw)}`);
