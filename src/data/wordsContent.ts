import raw from "../../assets/content/quranic-words.json";

/*
  The Quranic Words content, as bundled.

  Generated by scripts/coverage/build_words.py and kept apart from
  lessons.json on purpose: `npm run content:build` rewrites lessons.json from
  Neon, and Neon does not have this track yet, so living in that file would
  get it wiped on the next content build.

  Ids are fixed and are the contract with the server-to-be: lessons 1000 + stage
  (lessons.number 200 + stage), cards 100000 + the lemma's frequency rank, so
  re-cutting the stages moves a card between lessons without renumbering it.
  When the web repo seeds the track into Neon it must insert these exact ids.

  WHAT MAY BE SHOWN

  Every lemma form and skill example here is verbatim Quran Foundation
  word-by-word Arabic (source "qf-wbw"), shown with the attribution line. The
  English meanings are NOT in this file: Quran Foundation does not permit
  bundling them (2026-11-20), so each gloss carries only its ref and empty
  text, and src/data/wordGlosses.ts fills the text in after install, refreshed
  weekly. Stage
  titles and skill names are structural labels. Notes are
  empty placeholders with verified false; a note is shown only once it has
  text AND verified true, which today is never. canShowGloss and canShowNote
  are the one place that rule lives.
*/

export type Gloss = { text: string; source: string; ref: string; verified: boolean };
export type Note = { text: string | null; verified: boolean };

export type WordsLemma = {
  /* The lemma's frequency rank: stable when stages are re-cut. */
  id: number;
  /* Place on the path, 1-based. This, not the id, orders new words. */
  pos: number;
  cardId: number;
  stage: number;
  /* Quran words containing it, and ayahs containing it. */
  freq: number;
  ayahs: number;
  kind: "content" | "function";
  face: string;
  forms: string[];
  gloss: Gloss | null;
  audio: string | null;
  anchor: { ayah: string; word: number };
  group: string | null;
  note: Note;
};

export type WordsSkill = {
  id: number;
  key: string;
  stage: number;
  /* A neutral name ("Prefix wa-"). What a skill means is a note, and notes
     show only once verified. */
  label: string;
  words: number;
  examples: { arabic: string; gloss: string; source: string; ref: string }[];
  note: Note;
};

export type WordsStage = {
  stage: number;
  lessonId: number;
  number: number;
  titleEn: string;
  firstPosition: number;
  lastPosition: number;
  lemmas: number;
  skills: number[];
  tokens: number;
  coverageAfter: number;
  followableAfter: number;
};

export type WordsSurah = { surah: number; words: number; steps: [number, number][] };

export type WordsContent = {
  version: number;
  attribution: string;
  totals: { words: number; ayahs: number; followableShare: number };
  audioBase: string;
  stages: WordsStage[];
  lemmas: WordsLemma[];
  skills: WordsSkill[];
  path: { coverage: number[]; followable: number[] };
  surahs: WordsSurah[];
};

export const WORDS = raw as unknown as WordsContent;

export const WORDS_ATTRIBUTION = WORDS.attribution;

const BY_POS = [...WORDS.lemmas].sort((a, b) => a.pos - b.pos);

/* Lemma cards in path order: index k is the k+1th card of the path. */
export const PATH_CARD_IDS: readonly number[] = BY_POS.map((l) => l.cardId);

/* What a gap at each path position could cost, for knownAlongPath. */
export const PATH_WORD_WEIGHTS: readonly number[] = BY_POS.map((l) => l.freq);
export const PATH_AYAH_WEIGHTS: readonly number[] = BY_POS.map((l) => l.ayahs);

const byCard = new Map(WORDS.lemmas.map((l) => [l.cardId, l]));
export function lemmaForCard(cardId: number): WordsLemma | undefined {
  return byCard.get(cardId);
}

export function stageFor(n: number): WordsStage | undefined {
  return WORDS.stages.find((s) => s.stage === n);
}

export function skillsForStage(n: number): WordsSkill[] {
  return WORDS.skills.filter((s) => s.stage === n);
}

/* Glosses are shown only when verbatim from Quran Foundation, and only once fetched. */
export function canShowGloss(g: Gloss | null): g is Gloss {
  return g !== null && g.source === "qf-wbw" && g.text.trim().length > 0;
}

/* Hand-written notes are shown only once written and verified. */
export function canShowNote(n: Note): n is { text: string; verified: true } {
  return n.verified === true && typeof n.text === "string" && n.text.trim().length > 0;
}

/* Full word audio URL, from Quran Foundation's word-by-word audio. */
export function wordAudioUrl(path: string | null): string | null {
  return path ? WORDS.audioBase + path : null;
}

/*
  How many of every 100 words of the Quran contain one of a stage's words,
  rounded down so the intro never overstates it. Used by the stage intro.
*/
export function stageShare(stage: WordsStage): number {
  return Math.floor((100 * stage.tokens) / WORDS.totals.words);
}
